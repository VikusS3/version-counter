// @ts-check
import fs from "node:fs";
import path from "node:path";
import { ChangeFreqEnum } from "@astrojs/sitemap";

const rootDir = process.cwd();

// Load data files once at module initialization
/** @type {Array<{ href?: string; alias?: string; slug?: string; fecha_inicio?: string }>} */
let gamesData = [];
/** @type {Map<string, string>} */
const blogDates = new Map();

try {
  const gamesPath = path.resolve(rootDir, "src/data/games.json");
  if (fs.existsSync(gamesPath)) {
    gamesData = JSON.parse(fs.readFileSync(gamesPath, "utf8")).games || [];
  }
} catch (e) {
  console.warn("Could not load games.json for sitemap:", e);
}

// Index blog publishDates
try {
  const blogBaseDir = path.resolve(rootDir, "src/content/blog");
  for (const lang of ["en", "es"]) {
    const langDir = path.join(blogBaseDir, lang);
    if (fs.existsSync(langDir)) {
      const files = fs.readdirSync(langDir);
      for (const file of files) {
        if (!file.endsWith(".md")) continue;
        const slug = file.replace(/\.md$/, "");
        const content = fs.readFileSync(path.join(langDir, file), "utf8");
        const match = content.match(/publishDate:\s*["']?([^"'\n\r]+)["']?/);
        if (match) {
          blogDates.set(`${lang}:${slug}`, match[1].trim());
        }
      }
    }
  }
} catch (e) {
  console.warn("Could not load blog dates for sitemap:", e);
}

// Find the latest game update date
const latestGameDate = gamesData.reduce((latest, g) => {
  if (!g.fecha_inicio) return latest;
  const d = new Date(g.fecha_inicio);
  return d > latest ? d : latest;
}, new Date("2026-09-01T00:00:00Z"));

/**
 * Returns an ISO date string for lastmod, never in the future.
 * @param {Date | string} dateInput
 * @returns {string}
 */
function toSafeIsoDate(dateInput) {
  const date = dateInput instanceof Date ? dateInput : new Date(dateInput);
  if (isNaN(date.getTime())) {
    return new Date().toISOString();
  }
  const now = new Date();
  return (date > now ? now : date).toISOString();
}

/**
 * @typedef {import('@astrojs/sitemap').SitemapItem} SitemapItem
 */

/**
 * Serializes a sitemap item generated by @astrojs/sitemap.
 * Enriches each URL with x-default alternate, accurate lastmod, changefreq, and priority.
 * @param {SitemapItem} item
 * @returns {SitemapItem}
 */
export function serializeSitemapItem(item) {
  // 1. Ensure x-default hreflang parity with Layout.astro
  if (item.links && item.links.length > 0) {
    const enLink = item.links.find((l) => l.lang === "en");
    if (enLink && !item.links.some((l) => l.lang === "x-default")) {
      item.links.push({
        lang: "x-default",
        url: enLink.url,
      });
    }
  }

  const url = new URL(item.url);
  const pathname = url.pathname;
  const isEs = pathname.startsWith("/es/");
  const normalizedPath = isEs ? pathname.slice(3) : pathname; // e.g. /games/genshin/

  let priority = 0.5;
  let changefreq = ChangeFreqEnum.WEEKLY;
  let lastmod = toSafeIsoDate(latestGameDate);

  if (normalizedPath === "/" || normalizedPath === "") {
    // Homepage
    priority = 1.0;
    changefreq = ChangeFreqEnum.DAILY;
    lastmod = toSafeIsoDate(latestGameDate);
  } else if (normalizedPath.startsWith("/games/")) {
    // Game countdown pages
    priority = 0.9;
    changefreq = ChangeFreqEnum.DAILY;
    const gameSlug = normalizedPath.replace(/^\/games\//, "").replace(/\/$/, "");
    const game = gamesData.find(
      (g) => g.alias === gameSlug || g.href === `/${gameSlug}` || g.slug === gameSlug
    );
    if (game?.fecha_inicio) {
      lastmod = toSafeIsoDate(game.fecha_inicio);
    }
  } else if (normalizedPath === "/banners/") {
    // Banners overview
    priority = 0.9;
    changefreq = ChangeFreqEnum.DAILY;
    lastmod = toSafeIsoDate(latestGameDate);
  } else if (normalizedPath.startsWith("/blog/")) {
    const blogSlug = normalizedPath.replace(/^\/blog\//, "").replace(/\/$/, "");
    if (!blogSlug) {
      // Blog listing index
      priority = 0.8;
      changefreq = ChangeFreqEnum.WEEKLY;
      lastmod = toSafeIsoDate(latestGameDate);
    } else {
      // Blog article
      priority = 0.8;
      changefreq = ChangeFreqEnum.WEEKLY;
      const lang = isEs ? "es" : "en";
      const pubDate = blogDates.get(`${lang}:${blogSlug}`) || blogDates.get(`en:${blogSlug}`);
      if (pubDate) {
        lastmod = toSafeIsoDate(pubDate);
      }
    }
  } else if (normalizedPath.startsWith("/releases/")) {
    priority = 0.8;
    changefreq = ChangeFreqEnum.WEEKLY;
    try {
      const relStat = fs.statSync(path.resolve(rootDir, "src/data/releases.json"));
      lastmod = toSafeIsoDate(relStat.mtime);
    } catch {
      lastmod = toSafeIsoDate(latestGameDate);
    }
  } else if (normalizedPath === "/guides/") {
    priority = 0.7;
    changefreq = ChangeFreqEnum.WEEKLY;
    lastmod = toSafeIsoDate(latestGameDate);
  } else if (
    ["/about/", "/contact/", "/privacy/", "/terms/"].includes(normalizedPath)
  ) {
    priority = 0.4;
    changefreq = ChangeFreqEnum.MONTHLY;
    try {
      const pageFile = path.resolve(rootDir, "src/pages", normalizedPath.slice(1, -1) + ".astro");
      if (fs.existsSync(pageFile)) {
        lastmod = toSafeIsoDate(fs.statSync(pageFile).mtime);
      }
    } catch {
      // fallback to safe date
    }
  }

  item.priority = priority;
  item.changefreq = changefreq;
  item.lastmod = lastmod;

  return item;
}
